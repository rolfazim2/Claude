/** Достать все флаг-эмодзи из строки (региональные индикаторы — пары code points). */
export function extractFlags(text: string): string[] {
  const flags: string[] = [];
  // Региональные индикаторы: U+1F1E6..U+1F1FF идут парами.
  const chars = Array.from(text);
  for (let i = 0; i < chars.length - 1; i++) {
    const a = chars[i].codePointAt(0) ?? 0;
    const b = chars[i + 1].codePointAt(0) ?? 0;
    if (a >= 0x1f1e6 && a <= 0x1f1ff && b >= 0x1f1e6 && b <= 0x1f1ff) {
      flags.push(chars[i] + chars[i + 1]);
      i++;
    }
  }
  return flags;
}
